"""Synthetic PHD2 guide-log generator with known ground truth.

Simulates a mount with worm periodic error, polar-alignment drift, Dec
backlash, seeing noise, wind gusts, dithers and dropped frames, guided by a
PHD2-like controller, and writes the result in PHD2 log format (v2.5).
"""
from __future__ import annotations

import math
from dataclasses import dataclass, field, asdict
from datetime import datetime, timedelta

import numpy as np

SIDEREAL_DAY = 86164.0905


@dataclass
class SynthConfig:
    seed: int = 1
    start: str = "2026-10-14 21:00:00"
    duration_s: float = 3600.0
    exposure_s: float = 2.0
    overhead_s: float = 0.15
    pixel_scale: float = 4.83
    focal_length_mm: float = 160.0
    dec_deg: float = 20.0
    guide_speed_as_s: float = 7.52  # 0.5x sidereal
    mount: str = "EQMOD HEQ5/6 (ASCOM)"
    profile: str = "SynthHEQ5"
    worm_period_s: float = SIDEREAL_DAY / 135  # HEQ5
    # PE harmonics referred to the RA axis: (n, semi-amplitude arcsec, phase rad)
    pe_harmonics: list = field(default_factory=lambda: [(1, 8.0, 0.4), (2, 2.5, 1.3), (4, 1.0, -0.6)])
    gear_period_s: float = 0.0  # extra non-worm periodic component
    gear_amp_as: float = 0.0
    drift_ra_as_s: float = 0.003
    drift_dec_as_s: float = 0.006
    dec_backlash_ms: float = 800.0
    seeing_as: float = 0.6
    n_gusts: int = 3
    gust_amp_as: float = 5.0
    gust_len_s: float = 20.0
    dither_every_s: float = 0.0
    dither_px: float = 3.0
    drop_prob: float = 0.01
    ra_aggr: float = 0.7
    ra_hyst: float = 0.1
    dec_aggr: float = 0.9
    min_move_px: float = 0.15
    max_pulse_ms: float = 2500.0
    dec_guide: bool = True

    def truth(self) -> dict:
        d = asdict(self)
        cosd = math.cos(math.radians(self.dec_deg))
        ph = np.linspace(0, self.worm_period_s, 4000)
        curve = sum(a * np.sin(2 * np.pi * n * ph / self.worm_period_s + p) for n, a, p in self.pe_harmonics)
        d["pe_pp_axis"] = float(np.ptp(curve))
        d["pe_pp_sky"] = float(np.ptp(curve) * cosd)
        return d


def _play(u: float, y: float, b: float) -> float:
    h = b / 2
    if y < u - h:
        return u - h
    if y > u + h:
        return u + h
    return y


def generate(cfg: SynthConfig) -> str:
    rng = np.random.default_rng(cfg.seed)
    cosd = math.cos(math.radians(cfg.dec_deg))
    ps = cfg.pixel_scale
    x_rate = cfg.guide_speed_as_s * cosd / ps  # px/s
    y_rate = cfg.guide_speed_as_s / ps
    start = datetime.strptime(cfg.start, "%Y-%m-%d %H:%M:%S")

    gust_t = np.sort(rng.uniform(0.1, 0.9, cfg.n_gusts) * cfg.duration_s)
    gust_dir = rng.normal(size=(cfg.n_gusts, 2))

    def disturbance(t):
        ra = dec = 0.0
        for (t0, (a, b)) in zip(gust_t, gust_dir):
            if t0 <= t < t0 + cfg.gust_len_s:
                env = math.sin(math.pi * (t - t0) / cfg.gust_len_s)
                wob = math.sin(2 * math.pi * (t - t0) / 3.7)
                ra += cfg.gust_amp_as * env * wob * a
                dec += cfg.gust_amp_as * env * wob * b
        return ra, dec

    def pe_axis(t):
        v = sum(a * math.sin(2 * math.pi * n * t / cfg.worm_period_s + p) for n, a, p in cfg.pe_harmonics)
        if cfg.gear_period_s > 0:
            v += cfg.gear_amp_as * math.sin(2 * math.pi * t / cfg.gear_period_s)
        return v

    lines: list[str] = []
    w = lines.append
    w(f"PHD2 version 2.6.14 [Windows], Log version 2.5. Log enabled at {cfg.start}")
    w("INFO: Synthetic log generated by astrosense_guiding.synth")
    w("")
    w(f"Guiding Begins at {cfg.start}")
    w(f"Equipment Profile = {cfg.profile}")
    w("Dither = both axes, Dither scale = 1.000, Image noise reduction = none, Guide-frame time lapse = 0, Server enabled")
    w(f"Pixel scale = {ps:.2f} arc-sec/px, Binning = 1, Focal length = {cfg.focal_length_mm:.0f} mm")
    w("Search region = 15 px, Star mass tolerance = 50.0%")
    w("Camera = Synthetic, gain = 10, full size = 1280 x 960, have dark, dark dur = 2000, no defect map, pixel size = 3.8 um")
    w(f"Exposure = {int(cfg.exposure_s*1000)} ms")
    w(f"Mount = {cfg.mount}, connected, guiding enabled, xAngle = 0.0, xRate = {x_rate*1000/1000:.3f}, "
      f"yAngle = 90.0, yRate = {y_rate:.3f}, parity = +/+")
    w(f"X guide algorithm = Hysteresis, Hysteresis = {cfg.ra_hyst:.3f}, Aggression = {cfg.ra_aggr:.3f}, Minimum move = {cfg.min_move_px:.3f}")
    w(f"Y guide algorithm = Resist Switch, Minimum move = {cfg.min_move_px:.3f} Aggression = {cfg.dec_aggr*100:.0f}% FastSwitch = enabled")
    w("Backlash comp = disabled, pulse = 0 ms")
    w(f"Max RA duration = {int(cfg.max_pulse_ms)}, Max DEC duration = {int(cfg.max_pulse_ms)}, "
      f"DEC guide mode = {'Auto' if cfg.dec_guide else 'Off'}")
    w(f"RA Guide Speed = {cfg.guide_speed_as_s:.1f} a-s/s, Dec Guide Speed = {cfg.guide_speed_as_s:.1f} a-s/s, Cal Dec = {cfg.dec_deg:.1f}")
    w(f"RA = 3.00 hr, Dec = {cfg.dec_deg:.1f} deg, Hour angle = -1.00 hr, Pier side = East, Rotator pos = N/A, Alt = 55.0 deg, Az = 120.0 deg")
    w("Lock position = 640.000, 480.000, Star position = 640.000, 480.000, HFD = 2.50 px")
    w("Frame,Time,mount,dx,dy,RARawDistance,DECRawDistance,RAGuideDistance,DECGuideDistance,"
      "RADuration,RADirection,DECDuration,DECDirection,XStep,YStep,StarMass,SNR,ErrorCode")

    ra_corr_as = 0.0  # sky arcsec applied by RA pulses
    dec_cmd_ms = 0.0
    dec_mech_ms = -cfg.dec_backlash_ms / 2
    lock_ra = lock_dec = 0.0  # px
    prev_ra = 0.0
    dec_pending = 0
    dec_last_dir = 0
    next_dither = cfg.dither_every_s if cfg.dither_every_s > 0 else float("inf")
    t = 0.0
    frame = 0
    while t < cfg.duration_s:
        t += cfg.exposure_s + cfg.overhead_s + rng.normal(0, 0.02)
        frame += 1
        dra, ddec = disturbance(t)
        ra_sky = (pe_axis(t) + cfg.drift_ra_as_s * t) * cosd + ra_corr_as + dra
        dec_sky = cfg.drift_dec_as_s * t + dec_mech_ms * cfg.guide_speed_as_s / 1000 + ddec
        mass = 15000 * (1 + 0.05 * rng.normal())
        if rng.random() < cfg.drop_prob:
            w(f'{frame},{t:.3f},"DROP",,,,,,,,,,,,,0,0.00,2,"Star lost - low SNR"')
            continue
        ra_px = (ra_sky + rng.normal(0, cfg.seeing_as)) / ps - lock_ra
        dec_px = (dec_sky + rng.normal(0, cfg.seeing_as)) / ps - lock_dec
        # RA hysteresis controller (positive distance -> West pulse which reduces it)
        g_ra = (1 - cfg.ra_hyst) * ra_px + cfg.ra_hyst * prev_ra
        prev_ra = g_ra
        ra_move = cfg.ra_aggr * g_ra if abs(g_ra) >= cfg.min_move_px else 0.0
        ra_ms = min(abs(ra_move) / x_rate * 1000, cfg.max_pulse_ms)
        ra_dir = ("W" if ra_move > 0 else "E") if ra_ms > 0 else ""
        # Dec resist-switch-like controller
        dec_ms, dec_dir = 0.0, ""
        if cfg.dec_guide and abs(dec_px) >= cfg.min_move_px:
            d = 1 if dec_px > 0 else -1
            if d != dec_last_dir and dec_last_dir != 0 and abs(dec_px) < 3 * cfg.min_move_px:
                dec_pending = dec_pending + 1 if dec_pending * d >= 0 else 1
                allow = abs(dec_pending) >= 3
            else:
                allow = True
            if allow:
                dec_last_dir = d
                dec_pending = 0
                dec_ms = min(cfg.dec_aggr * abs(dec_px) / y_rate * 1000, cfg.max_pulse_ms)
                dec_dir = "S" if d > 0 else "N"
        rag = ra_move if ra_ms else 0.0
        deg = (dec_px * cfg.dec_aggr) if dec_ms else 0.0
        w(f'{frame},{t:.3f},"Mount",{ra_px:.3f},{dec_px:.3f},{ra_px:.3f},{dec_px:.3f},{rag:.3f},{deg:.3f},'
          f'{int(round(ra_ms))},{ra_dir},{int(round(dec_ms))},{dec_dir},,,{mass:.0f},{25+rng.normal():.2f},0')
        # apply pulses (W reduces positive RA distance, S reduces positive Dec distance)
        if ra_ms:
            ra_corr_as += (-1 if ra_dir == "W" else 1) * ra_ms / 1000 * x_rate * ps
        if dec_ms:
            dec_cmd_ms += (-1 if dec_dir == "S" else 1) * dec_ms
            dec_mech_ms = _play(dec_cmd_ms, dec_mech_ms, cfg.dec_backlash_ms)
        if t >= next_dither:
            ddx, ddy = rng.uniform(-cfg.dither_px, cfg.dither_px, 2)
            lock_ra += ddx
            lock_dec += ddy
            w(f"INFO: DITHER by {ddx:.3f}, {ddy:.3f}, new lock pos = {640+lock_ra:.3f}, {480+lock_dec:.3f}")
            w("INFO: SETTLING STATE CHANGE, Settling started")
            next_dither += cfg.dither_every_s
    end = start + timedelta(seconds=t)
    w(f"Guiding Ends at {end:%Y-%m-%d %H:%M:%S}")
    w("")
    w(f"Log closed at {end:%Y-%m-%d %H:%M:%S}")
    return "\n".join(lines) + "\n"
